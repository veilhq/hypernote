"""Build Hypernote - concatenates Hyperkit CSS + local CSS and JS into shell.html.

Follows the same Hyperkit integration pattern as Hyperfield/Hyperagent:
- Hyperkit CSS loaded first (tokens, primitives, globals, components, cards,
  content, accessibility) so app-local CSS can override via cascade order
- Hyperkit JS modules loaded before local JS
- Output written to generated_html.py as an importable HTML string

Hypernote consumes more of the shared layer than Hyperfield because it reuses
the context-menu, prompt-dialog, modal, floating-panel, list-row, status-chip,
and dir-surface primitives rather than hand-rolling them.

Usage: python build.py
Output: Updates the HTML variable in generated_html.py
"""
import glob
import sys
from pathlib import Path

ROOT = Path(__file__).parent
HYPERKIT_DIR = ROOT.parent / ".hyperkit"
HYPERKIT_CSS_DIR = HYPERKIT_DIR / "css"
HYPERKIT_JS_DIR = HYPERKIT_DIR / "js"

# Self-hosted @font-face rules (data URIs) shared by every app.
sys.path.insert(0, str(HYPERKIT_DIR / "python"))
from hyperkit_css import hyperkit_css  # noqa: E402
from design_lint import report as report_design_lint  # noqa: E402

# JS modules Hypernote actually uses.
HYPERKIT_JS_MODULES = ["utils.js", "toast.js", "tooltip.js", "context-menu.js"]


def concat_hyperkit_css():
    """Read the shared HyperKit CSS modules in cascade order. Fails loudly if missing."""
    return hyperkit_css(("components", "content", "cards"), app="Hypernote")


def concat_local_css():
    """Concatenate local CSS files in sort order."""
    files = sorted(glob.glob(str(ROOT / "assets/css/*.css")))
    return "\n".join(Path(f).read_text(encoding="utf-8") for f in files)


def render_hyperkit_js_blocks():
    """Emit one <script> block per Hyperkit JS module."""
    if not HYPERKIT_JS_DIR.exists():
        raise FileNotFoundError(
            f"Hyperkit JS directory missing: {HYPERKIT_JS_DIR}\n"
            "Hypernote's build.py requires .hyperspace/.hyperkit/js/."
        )
    blocks = []
    for name in HYPERKIT_JS_MODULES:
        f = HYPERKIT_JS_DIR / name
        if not f.exists():
            raise FileNotFoundError(f"Hyperkit JS module missing: {f}")
        content = f.read_text(encoding="utf-8")
        blocks.append(f"<!-- hyperkit/{name} -->\n<script>\n{content}\n</script>")
    return "\n".join(blocks)


def render_local_js_blocks():
    """Emit one <script> block per local JS module (sorted)."""
    files = sorted(glob.glob(str(ROOT / "assets/js/*.js")))
    blocks = []
    for f in files:
        content = Path(f).read_text(encoding="utf-8")
        name = Path(f).name
        blocks.append(f"<!-- {name} -->\n<script>\n{content}\n</script>")
    return "\n".join(blocks)


def read_logo_svg():
    """Read the inline logo mark for the topbar brand (inherits currentColor)."""
    f = ROOT / "assets" / "hypernote.svg"
    if not f.exists():
        return ""
    return f.read_text(encoding="utf-8")


def build():
    css = concat_hyperkit_css() + "\n" + concat_local_css()
    js_blocks = render_hyperkit_js_blocks() + "\n" + render_local_js_blocks()
    shell = (ROOT / "assets" / "shell.html").read_text(encoding="utf-8")
    html = (
        shell.replace("{{CSS}}", css)
        .replace("{{JS_BLOCKS}}", js_blocks)
        .replace("{{LOGO_SVG}}", read_logo_svg())
    )

    out = ROOT / "generated_html.py"
    out.write_text(
        f'"""Auto-generated by build.py - do not edit."""\n\nHTML = {repr(html)}\n',
        encoding="utf-8",
    )

    css_bytes = len(css)
    js_files = sorted(glob.glob(str(ROOT / "assets/js/*.js")))
    js_total = sum(len(Path(f).read_text(encoding="utf-8")) for f in js_files)
    print(
        f"Built: {css_bytes} bytes CSS, {js_total} bytes JS "
        f"across {len(js_files)} local modules "
        f"+ {len(HYPERKIT_JS_MODULES)} Hyperkit modules -> generated_html.py"
    )


if __name__ == "__main__":
    report_design_lint("Hypernote", ROOT)  # exits 1 before anything is written
    build()
